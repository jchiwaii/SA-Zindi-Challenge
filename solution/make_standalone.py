"""Create a single-file inference entry point using only public Python packages."""

import ast
from pathlib import Path
from audit_data import COLS

BASE = Path(__file__).resolve().parent


def selected_definitions(filename, names):
    source = (BASE / filename).read_text()
    tree = ast.parse(source)
    nodes = {
        node.name: node for node in tree.body if isinstance(node, (ast.FunctionDef, ast.ClassDef))
    }
    return "\n\n".join(ast.get_source_segment(source, nodes[name]) for name in names)


def main():
    header = '''"""Standalone saved-weight inference. Generated by make_standalone.py.

Uses only publicly available packages; no custom package installation is needed.
Competition test inputs are used for inference only.
"""
import argparse
import hashlib
import json
import resource
import time
import warnings
from pathlib import Path
import joblib
import numpy as np
import pandas as pd
import torch
from torch import nn
from catboost import CatBoostRegressor

BASE = Path(__file__).resolve().parent
'''
    chunks = [header, f"COLS = {COLS!r}"]
    chunks.append(
        selected_definitions("acoustic_model.py", ["energy", "feature_batch", "features"])
    )
    chunks.append(
        selected_definitions("neural.py", ["AcousticNet", "raw_inputs", "neural_predict"])
    )
    chunks.append(selected_definitions("select_and_audit.py", ["Ensemble"]))
    chunks.append(selected_definitions("predict.py", ["sha256", "main"]))
    chunks.append('if __name__ == "__main__":\n    main()\n')
    target = BASE / "submission_inference.py"
    target.write_text("\n\n".join(chunks))
    print("Generated", target)


if __name__ == "__main__":
    main()
